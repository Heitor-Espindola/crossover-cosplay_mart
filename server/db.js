let ready;


export async function initDb() {
  if (!ready) {
    ready = (async () => {
      for (const sql of SCHEMA) {
        await pool.query(sql);
      }

      // Sincroniza as sequências após inserções com IDs explícitos.
      const identityTables = [
        'users',
        'addresses',
        'order_items',
        'reviews',
        'loadouts',
      ];

      for (const table of identityTables) {
        await pool.query(`
          SELECT setval(
            pg_get_serial_sequence('public.${table}', 'id'),
            GREATEST(COALESCE((SELECT MAX(id) FROM public.${table}), 1), 1),
            EXISTS (SELECT 1 FROM public.${table})
          )
        `);
      }

      return pool;
    })().catch((error) => {
      ready = null;
      throw error;
    });
  }

  return ready;
}


function cleanValue(value) {
  if (value === undefined) return null;

  if (
    value !== null &&
    typeof value === 'object' &&
    !(value instanceof Date) &&
    !Buffer.isBuffer(value)
  ) {
    return JSON.stringify(value);
  }

  return value;
}

function convertSql(sql, params) {
  const values = [];
  const named = !Array.isArray(params) &&
    params !== undefined &&
    params !== null &&
    typeof params === 'object';

  let index = 0;

  const converted = sql.replace(
    /@([a-zA-Z_][a-zA-Z0-9_]*)|\?/g,
    (match, name) => {
      index += 1;

      const value = named
        ? params[name]
        : params?.[index - 1];

      values.push(cleanValue(value));

      return `$${index}`;
    },
  );

  return { text: converted, values };
}

function createAdapter(queryable) {
  return {
    prepare(sql) {
      return {
        async all(...args) {
          const params = args.length === 0
            ? undefined
            : args.length === 1
              ? args[0]
              : args;

          const { text, values } = convertSql(sql, params);
          const result = await queryable.query(text, values);

          return result.rows;
        },

        async get(...args) {
          const rows = await this.all(...args);
          return rows[0];
        },

        async run(...args) {
          const params = args.length === 0
            ? undefined
            : args.length === 1
              ? args[0]
              : args;

          let { text, values } = convertSql(sql, params);

          const returnsGeneratedId =
            /^\s*INSERT\s+INTO\s+(users|addresses|loadouts)\b/i.test(text) &&
            !/\bRETURNING\b/i.test(text);

          if (returnsGeneratedId) {
            text += ' RETURNING id';
          }

          const result = await queryable.query(text, values);

          return {
            changes: result.rowCount ?? 0,
            lastInsertRowid: result.rows?.[0]?.id,
          };
        },
      };
    },

    async exec(sql) {
      const statements = sql
        .split(';')
        .map((statement) => statement.trim())
        .filter(Boolean);

      for (const statement of statements) {
        await queryable.query(statement);
      }
    },
  };
}

const adapter = createAdapter(pool);

export const db = {
  prepare: adapter.prepare,
  exec: adapter.exec,
};

export async function exec(sql) {
  return adapter.exec(sql);
}

export async function transaction(callback) {
  await initDb();

  const client = await pool.connect();

  try {
    await client.query('BEGIN');

    const tx = createAdapter(client);

    const result = await callback(tx);

    await client.query('COMMIT');

    return result;
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

export function json(value) {
  if (value === null || value === undefined) return null;
  return JSON.stringify(value);
}

export function parseJson(value, fallback) {
  if (!value) return fallback;

  try {
    return JSON.parse(value);
  } catch {
    return fallback;
  }
}
